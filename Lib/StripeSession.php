namespace FacturaScripts\Plugins\ImportadorStripe\Lib;

/**
 * Envuelve la sesión nativa de PHP usada por el plugin para conservar el estado entre peticiones.
 * FacturaScripts 2026 no expone una sesión persistente, por lo que se mantiene el uso de $_SESSION.
 */
class StripeSession
{
    public static function start(): void
    {
        if (session_status() === PHP_SESSION_NONE) {
            session_start();
        }
    }

    public static function get(string $key, $default = null)
    {
        return $_SESSION[$key] ?? $default;
    }

    public static function set(string $key, $value): void
    {
        $_SESSION[$key] = $value;
    }

    public static function has(string $key): bool
    {
        return isset($_SESSION[$key]);
    }
}
